"""Generate UI translations; --check validates committed output without writing."""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'lib' / 'l10n'
catalogs = {code: json.loads((root / f'ui_{code}.json').read_text()) for code in ('en', 'de')}
assert catalogs['en'].keys() == catalogs['de'].keys(), 'Locale keys differ'
for key, value in catalogs['en'].items():
    translated = catalogs['de'][key]
    assert translated.strip(), f'Empty translation: {key}'
    assert set(re.findall(r'\{[a-zA-Z]+\}', value)) == set(re.findall(r'\{[a-zA-Z]+\}', translated)), f'Placeholder mismatch: {key}'
def dart_string(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
lines = ['// Generated by tool/generate_ui_catalog.py. Edit ui_en.json / ui_de.json.', '']
for code, values in catalogs.items():
    lines.append(f'const ui{code.title()} = <String, String>{{')
    lines.extend(f'  {dart_string(key)}: {dart_string(value)},' for key, value in sorted(values.items()))
    lines.extend(['};', ''])
output = '\n'.join(lines)
target = root / 'ui_catalog.g.dart'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Run tool/generate_ui_catalog.py to regenerate catalog'
else:
    target.write_text(output)
print(f'PASS {len(catalogs["en"])} UI keys: locale parity, placeholders and generated catalog')
